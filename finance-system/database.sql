  DROP INDEX IF EXISTS user_id,
  ADD COLUMN IF NOT EXISTS priority TINYINT NOT NULL DEFAULT 2,
  ADD COLUMN IF NOT EXISTS kind VARCHAR(12) NOT NULL DEFAULT 'general';
CREATE TABLE IF NOT EXISTS debts (
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, name VARCHAR(80) NOT NULL,
  kind ENUM('credit_card','student_loan','personal_loan','other') NOT NULL DEFAULT 'personal_loan',
  balance DECIMAL(14,2) NOT NULL, rate DECIMAL(6,2) NOT NULL DEFAULT 0, min_payment DECIMAL(12,2) NOT NULL DEFAULT 0,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS assets (
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, name VARCHAR(80) NOT NULL,
  kind ENUM('asset','liability') NOT NULL DEFAULT 'asset', value DECIMAL(14,2) NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS networth_history (
  user_id INT NOT NULL, snap_date DATE NOT NULL, assets DECIMAL(14,2) NOT NULL, liabilities DECIMAL(14,2) NOT NULL,
  PRIMARY KEY (user_id, snap_date), FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS rules (
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, keyword VARCHAR(60) NOT NULL, category VARCHAR(50) NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS tuition (
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, item VARCHAR(80) NOT NULL,
  amount DECIMAL(12,2) NOT NULL, paid DECIMAL(12,2) NOT NULL DEFAULT 0, due_date DATE NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS groups_ (
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL, kind ENUM('couple','family','roommates','other') NOT NULL DEFAULT 'roommates', owner_id INT NOT NULL);
CREATE TABLE IF NOT EXISTS group_members (
  group_id INT NOT NULL, user_id INT NOT NULL, role ENUM('owner','editor','viewer') NOT NULL DEFAULT 'editor',
  PRIMARY KEY (group_id, user_id), FOREIGN KEY (group_id) REFERENCES groups_(id) ON DELETE CASCADE, FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS group_expenses (
  id INT AUTO_INCREMENT PRIMARY KEY, group_id INT NOT NULL, paid_by INT NOT NULL, description VARCHAR(120) NOT NULL,
  amount DECIMAL(12,2) NOT NULL, spent_on DATE NOT NULL, FOREIGN KEY (group_id) REFERENCES groups_(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS login_log (
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NULL, email VARCHAR(150), ip VARCHAR(45), ua VARCHAR(200),
  ok TINYINT NOT NULL, at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, INDEX (ip, at), INDEX (user_id));
CREATE TABLE IF NOT EXISTS audit_log (
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NULL, action VARCHAR(80) NOT NULL, detail VARCHAR(255) DEFAULT '',
  ip VARCHAR(45), at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, INDEX (user_id));
CREATE TABLE IF NOT EXISTS support (
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, kind ENUM('ticket','feedback') NOT NULL, subject VARCHAR(120) NOT NULL,
  body TEXT NOT NULL, status ENUM('open','closed') NOT NULL DEFAULT 'open', at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS app_log (
  id INT AUTO_INCREMENT PRIMARY KEY, kind ENUM('error','page') NOT NULL, page VARCHAR(80), detail VARCHAR(255) DEFAULT '', ms INT DEFAULT 0,
  at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, INDEX (kind, at));
