CREATE TABLE IF NOT EXISTS accounts (
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL,
  name VARCHAR(80) NOT NULL, type ENUM('bank','cash','savings','credit_card','mobile_wallet') NOT NULL DEFAULT 'bank',
  opening_balance DECIMAL(14,2) NOT NULL DEFAULT 0,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE);
ALTER TABLE transactions
  ADD COLUMN IF NOT EXISTS account_id INT NULL,
  ADD COLUMN IF NOT EXISTS notes TEXT NULL,
  ADD COLUMN IF NOT EXISTS receipt VARCHAR(80) NULL,
  ADD COLUMN IF NOT EXISTS split_group VARCHAR(20) NULL;
CREATE TABLE IF NOT EXISTS recurring (
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, type ENUM('income','expense') NOT NULL,
  category VARCHAR(50) NOT NULL, amount DECIMAL(12,2) NOT NULL, description VARCHAR(255) DEFAULT '',
  account_id INT NULL, frequency ENUM('once','daily','weekly','monthly','yearly') NOT NULL DEFAULT 'monthly',
  next_date DATE NOT NULL, active TINYINT NOT NULL DEFAULT 1,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS budgets (
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, category VARCHAR(50) NOT NULL,
  period ENUM('weekly','monthly','semester','custom') NOT NULL DEFAULT 'monthly',
  amount DECIMAL(12,2) NOT NULL, start_date DATE NULL, end_date DATE NULL, rollover TINYINT NOT NULL DEFAULT 0,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE);
ALTER TABLE goals
